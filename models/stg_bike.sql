WITH STAGE_BIKE_CTE AS(

SELECT DISTINCT 
RIDE_ID ,
	TO_TIMESTAMP(REPLACE(STARTED_AT,'"','')) AS STARTED_AT,
	TO_TIMESTAMP(REPLACE(ENDED_AT,'"','')) AS ENDED_AT ,
	REPLACE(START_STATION_NAME,'"','') AS START_STATION_NAME ,
	START_STATIO_ID ,
	REPLACE(END_STATION_NAME,'"','') AS END_STATION_NAME ,
	END_STATION_ID ,
	START_LAT ,
	START_LNG ,
	END_LAT ,
	END_LNG ,
	REPLACE(MEMBER_CSUAL ,'"','') AS MEMBER_CSUAL
FROM {{ source('DEMO', 'BIKE') }}
WHERE REPLACE(RIDE_ID,'"','') <> 'bikeid'

)

SELECT * FROM STAGE_BIKE_CTE

