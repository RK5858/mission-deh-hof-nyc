WITH TRIP_CTE AS (

SELECT RIDE_ID
      ,DATE(STARTED_AT) AS TRIP_DATE
      ,START_STATIO_ID AS START_STATION_ID
      ,END_STATION_ID
      ,MEMBER_CSUAL AS MEMBER_CASUAL
      ,TIMESTAMPDIFF(SECOND,STARTED_AT,ENDED_AT)
FROM {{ ref('stg_bike') }}

)

SELECT * FROM TRIP_CTE